// dither.js — pure multi-tone dithering engine. No DOM, importable in node and browser.

export function hexToRgb(hex) {
  const h = hex.replace('#', '');
  return [
    parseInt(h.slice(0, 2), 16),
    parseInt(h.slice(2, 4), 16),
    parseInt(h.slice(4, 6), 16),
  ];
}

export function buildPalette(hexArray) {
  return hexArray.map(hexToRgb);
}

export function luminance(r, g, b) {
  return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255; // 0..1
}

export function applyBC(L, brightness, contrast) {
  const f = 1 + contrast / 100;            // -100→0, 0→1, 100→2
  const v = (L - 0.5) * f + 0.5 + brightness / 100;
  return v < 0 ? 0 : v > 1 ? 1 : v;
}

export function bandIndex(L, levels, thresholds) {
  const t = (thresholds && thresholds.length === levels - 1)
    ? thresholds
    : Array.from({ length: levels - 1 }, (_, i) => (i + 1) / levels);
  let idx = 0;
  for (let i = 0; i < t.length; i++) if (L >= t[i]) idx = i + 1;
  return idx; // 0..levels-1
}

// Ordered Bayer matrices generated by the standard recursion, normalized to [0,1).
// Levels L1..L5 = sizes 2, 4, 8, 16, 32 (higher = finer dither pattern).
function doubleBayer(M) {
  const n = M.length, off = [[0, 2], [3, 1]], R = [];
  for (let i = 0; i < 2 * n; i++) {
    R[i] = [];
    for (let j = 0; j < 2 * n; j++) R[i][j] = 4 * M[i % n][j % n] + off[Math.floor(i / n)][Math.floor(j / n)];
  }
  return R;
}
export const BAYER = (() => {
  const norm = m => m.map(r => r.map(v => v / (m.length * m.length)));
  let M = [[0, 2], [3, 1]];
  const out = { 2: norm(M) };
  for (const size of [4, 8, 16, 32]) { M = doubleBayer(M); out[size] = norm(M); }
  return out;
})();

export function ditherImageData(src, opts) {
  const { width, height, data } = src;
  const {
    levels, palette, algorithm,
    bayerSize = 4, brightness = 0, contrast = 0, thresholds, curveLUT, alphaForBand,
  } = opts;
  const out = { width, height, data: new Uint8ClampedArray(data.length) };
  const od = out.data;
  const bands = new Uint8Array(width * height);
  out.bands = bands;
  const pick = idx => palette[idx] || palette[palette.length - 1];
  const tone = L => {
    const v = applyBC(L, brightness, contrast);
    return curveLUT ? curveLUT[Math.round(v * 255)] : v;
  };

  if (algorithm === 'bayer') {
    const M = BAYER[bayerSize] || BAYER[4];
    const n = M.length;
    const amp = 1 / levels;
    for (let y = 0; y < height; y++) {
      for (let x = 0; x < width; x++) {
        const p = (y * width + x) * 4;
        const L = tone(luminance(data[p], data[p + 1], data[p + 2]));
        const Lm = L + amp * (M[y % n][x % n] - 0.5);
        const idx = bandIndex(Lm, levels, thresholds);
        bands[y * width + x] = idx;
        const c = pick(idx);
        od[p] = c[0]; od[p + 1] = c[1]; od[p + 2] = c[2];
        od[p + 3] = alphaForBand ? alphaForBand[idx] : 255;
      }
    }
    return out;
  }

  // error-diffusion: floyd | atkinson
  const buf = new Float32Array(width * height);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const p = (y * width + x) * 4;
      buf[y * width + x] = tone(luminance(data[p], data[p + 1], data[p + 2]));
    }
  }
  const KERNELS = {
    floyd: [[1, 0, 7 / 16], [-1, 1, 3 / 16], [0, 1, 5 / 16], [1, 1, 1 / 16]],
    atkinson: [[1, 0, 1 / 8], [2, 0, 1 / 8], [-1, 1, 1 / 8], [0, 1, 1 / 8], [1, 1, 1 / 8], [0, 2, 1 / 8]],
  };
  const K = KERNELS[algorithm];
  if (!K) throw new Error(`unknown algorithm: ${algorithm}`);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = y * width + x;
      const L = buf[i];
      const idx = bandIndex(L, levels, thresholds);
      bands[i] = idx;
      const q = idx / (levels - 1);
      const err = L - q;
      for (const [dx, dy, w] of K) {
        const nx = x + dx, ny = y + dy;
        if (nx >= 0 && nx < width && ny >= 0 && ny < height) buf[ny * width + nx] += err * w;
      }
      const c = pick(idx);
      const p = i * 4;
      od[p] = c[0]; od[p + 1] = c[1]; od[p + 2] = c[2];
      od[p + 3] = alphaForBand ? alphaForBand[idx] : 255;
    }
  }
  return out;
}
